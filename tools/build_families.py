#!/usr/bin/env python3
"""Builds families.js from the family manifests: families/order.json + families/<id>.json (family_template.md §2.1 +
words/music/aura). The manifests are the ONE source for family names, labels, animal cards, colour chips, name lists,
creature profile, talents, memory deck, music keys and note tints. Add a family = add families/<id>.json + its id in
families/order.json, then run this. Internal ids (slyte / whimber) never change; labels are data."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FD = os.environ.get('ECHO_FAMILIES_DIR') or os.path.join(ROOT, 'families')
OUT = os.environ.get('ECHO_FAMILIES_OUT') or os.path.join(ROOT, 'families.js')
ORDER = json.load(open(os.path.join(FD, 'order.json')))['order']
M = {f: json.load(open(os.path.join(FD, f + '.json'))) for f in ORDER}
_PX = os.path.join(ROOT, 'px', 'origin')
icon = lambda a, m: a if os.path.exists(os.path.join(_PX, a + '.png')) else m.get('icon_fallback', a)   # card icon: px/origin/<animal>.png, else the family's stand-in
BASE = ('label', 'plural', 'default_name', 'kind', 'look_base', 'look_default', 'looks', 'dialogue', 'sprite', 'look')
animals, order = {}, []
for f in ORDER:
  m = M[f]
  for a in m['animalOrder']:
    v = m['animals'][a]; animals[a] = {'label': v['label'], 'word': v['word'], 'family': f, 'default_name': v['default_name'], 'look': v['look'], 'icon': icon(a, m)}; order.append(a)
    assert v['look'] in m['looks'], (a, f, v['look'])   # every card look must be built (or fall back to look_default)
out = {'order': ORDER, 'animals': animals, 'animalOrder': order}
for f in ORDER:
  m = M[f]
  out[f] = dict({k: m[k] for k in BASE}, id=f, names=m['names'],
                chips=[{'id': c['word'], 'label': c['label'], 'hex': c['hex'], 'ramp': c['id'], 'real': c['real']} for c in m['colours']],
                profile={k: m['profile'][k] for k in ('locomotion', 'home', 'bed', 'farewellRoute', 'place', 'talents', 'talentArt', 'game') if k in m['profile']},
                creature=m.get('creature'), music=m.get('music'), notes=(m.get('aura') or {}).get('notes'), games=m.get('games'), scene=m.get('scene'))
js = ('// GENERATED by tools/build_families.py from families/*.json (the family manifests). Do not hand-edit.\n'
      '// A family rename is a data-only change in its manifest (ids stay slyte / whimber).\n'
      'window.FAMILIES=' + json.dumps(out, ensure_ascii=False) + ';\n'
      'FAMILIES.byKind={};for(const f of FAMILIES.order)FAMILIES.byKind[FAMILIES[f].kind]=FAMILIES[f];\n'
      'FAMILIES.list=(sep)=>FAMILIES.order.map(f=>(/^[aeiou]/i.test(FAMILIES[f].label)?"an ":"a ")+FAMILIES[f].label).join(sep||" or ");   // "a Howling or a Wingsong"\n'
      'FAMILIES.idOf=(k)=>FAMILIES[k]?k:(FAMILIES.byKind[k]||FAMILIES[FAMILIES.order[0]]).id;   // kind or id -> family id ("fox" -> "slyte")\n'
      'FAMILIES.of=(k)=>FAMILIES[FAMILIES.idOf(k)];\n')
open(OUT, 'w').write(js)
print('families.js', len(js), 'bytes;', {f: len(out[f]['names']) for f in ORDER})
