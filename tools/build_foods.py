# foods.js from aliveness/foods.json: only foods whose 16 px icon exists are offered (F2 v1: 12 new icons).
import json,os
F=json.load(open('/workspace/echo/aliveness/foods.json'))
out={'tiers':F['tiers'],'slyte':[],'whimber':[]}
for sp in ('slyte','whimber'):
    for x in F[sp]:
        ic=x['icon'];ic='i_'+ic[4:] if ic.startswith('new:') else ic
        if not os.path.exists(f'px/{ic}.png'):continue
        out[sp].append({k:x[k] for k in ('id','name','emoji','group','taste','eat_style','delivery')}|{'icon':ic})
open('foods.js','w').write('// generated by tools/build_foods.py from aliveness/foods.json (do not edit by hand)\nwindow.FOODS='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
print({sp:[x['id'] for x in out[sp]] for sp in ('slyte','whimber')})
