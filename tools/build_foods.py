# foods.js from aliveness/foods.json: only foods whose 16 px icon exists are offered (F2 v1: 12 new icons).
import json,os
F=json.load(open('/workspace/echo/aliveness/foods.json'))
missing=[(sp,x['id']) for sp in ('slyte','whimber') for x in F[sp]
         if not os.path.exists('px/'+('i_'+x['icon'][4:] if x['icon'].startswith('new:') else x['icon'])+'.png')]
if missing: print('WARNING foods without icon:',missing)
out={'tiers':F['tiers'],'slyte':[],'whimber':[]}
for sp in ('slyte','whimber'):
    for x in F[sp]:
        ic=x['icon'];ic='i_'+ic[4:] if ic.startswith('new:') else ic
        if not os.path.exists(f'px/{ic}.png'):continue
        out[sp].append({k:x[k] for k in ('id','name','emoji','group','taste','eat_style','delivery')}|{'icon':ic})
# families with no aliveness/foods.json list (Purrlings on): manifest profile.foods + foods{tiers,new}; existing entries borrowed by id
ALL={x['id']:x for sp in ('slyte','whimber') for x in out[sp]}
for f in json.load(open('families/order.json'))['order']:
    if f in out:continue
    m=json.load(open(f'families/{f}.json'));T=m['foods']['tiers'];NEW={x['id']:x for x in m['foods']['new']};out[f]=[]
    for i in m['profile']['foods']:
        x=dict(NEW.get(i) or ALL.get(i) or {})
        if not x or not os.path.exists(f"px/{x['icon']}.png"):print('WARNING',f,'food without entry/icon:',i);continue
        x['taste']=T[i];out[f].append(x)
open('foods.js','w').write('// generated by tools/build_foods.py from aliveness/foods.json (do not edit by hand)\nwindow.FOODS='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
print({sp:len(out[sp]) for sp in out if sp!='tiers'})
