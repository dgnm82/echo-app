#!/usr/bin/env python3
"""Builds games_tuning.js: the ONE data file for Games v2 tuning (games_v2/spec.md, decided Oct 12 2026 7:55 PM).
Source: /workspace/echo/game_design/games_v2/tuning/tuning.json (written by games_v2/src/curves.py from tuning.py).
Same pattern as tools/build_families.py: a generated window global that also works with require() in node tests.
Usage: python3 tools/build_games_tuning.py [out.js]   (default: games_tuning.js in the repo root)"""
import json, os, sys
SRC = '/workspace/echo/game_design/games_v2/tuning/tuning.json'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'games_tuning.js')
T = json.load(open(SRC))
js = ('// GENERATED by tools/build_games_tuning.py from games_v2/tuning/tuning.json. Edit the source + rebuild, never by hand.\n'
      '(function(W){const T=' + json.dumps(T, separators=(',', ':'), ensure_ascii=False) + ';\n'
      'W.GAMES_TUNING=T;if(typeof module!=="undefined")module.exports=T})(typeof window!=="undefined"?window:globalThis);\n')
open(out, 'w').write(js); print('wrote', out, len(js), 'bytes')
