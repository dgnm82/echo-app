# need_tags.js from aliveness/need_map.json: existing ambient lines + conversations tagged with need / weather states.
import json
def h(s):
    x=5381
    for ch in s.encode('utf-16-le').decode('utf-16-le'):
        pass
    x=5381
    # JS charCodeAt works on UTF-16 code units
    u=s.encode('utf-16-le');cu=[u[i]|(u[i+1]<<8) for i in range(0,len(u),2)]
    for c in cu:x=((x<<5)+x+c)&0xffffffff
    x=x-(1<<32) if x>=1<<31 else x
    x&=0xffffffff
    d='0123456789abcdefghijklmnopqrstuvwxyz';o=''
    while True:
        o=d[x%36]+o;x//=36
        if not x:break
    return o
M=json.load(open('/workspace/echo/aliveness/need_map.json'))['states']
T={'slyte':{'barks':{},'convs':{}},'whimber':{'barks':{},'convs':{}}}
def add(sp,st,bks,cvs):
    for b in bks or []:
        if b['ref'].startswith('ambient['):T[sp]['barks'].setdefault('ambient:'+h(b['text']),[]).append(st)
    for c in cvs or []:T[sp]['convs'].setdefault(c['id'],[]).append(st)
for st,v in M.items():
    for sp in ('slyte','whimber'):
        d=v[sp]
        if st=='weather':
            for w,bks in d['existing_barks'].items():add(sp,'w_'+w,bks,d['existing_conversations'].get(w))
        elif st in('hungry','cuddly','playful','sleepy','content'):add(sp,st,d.get('existing_barks'),d.get('existing_conversations'))
# check the hashes against the repo's dialogue
for sp in ('slyte','whimber'):
    amb={'ambient:'+h(l['text']) for l in json.load(open(f'dialogue/{sp}.json'))['barks']['ambient']}
    miss=[k for k in T[sp]['barks'] if k not in amb];assert not miss,(sp,miss)
open('need_tags.js','w').write('// generated by tools/build_need_tags.py from aliveness/need_map.json\nwindow.NEED_TAGS='+json.dumps(T,ensure_ascii=False,separators=(',',':'))+';\n')
print({sp:(len(T[sp]['barks']),len(T[sp]['convs'])) for sp in T})
